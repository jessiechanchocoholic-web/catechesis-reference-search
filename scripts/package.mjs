import { deflateRawSync } from "node:zlib";
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ignoreDirs = new Set(["node_modules", "dist", ".git", ".wrangler", ".cursor", "coverage", "pkg"]);
const secretPattern =
  /(?:POE_API_KEY|GEMINI_API_KEY|CLOUDFLARE_API_TOKEN|CLOUDFLARE_API_KEY)\s*[:=]\s*["']?(?!YOUR_|MY_|your_)[A-Za-z0-9_\-]{16,}/;

function crc32(buffer) {
  let crc = ~0;
  for (let index = 0; index < buffer.length; index += 1) {
    crc ^= buffer[index];
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
    }
  }
  return ~crc >>> 0;
}

function dosStamp(date) {
  const time = (date.getHours() << 11) | (date.getMinutes() << 5) | (date.getSeconds() >> 1);
  const day = ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
  return { time, day };
}

function skipFile(name) {
  if (name === ".env" || name === ".dev.vars" || name === "archive.generated.ts") return true;
  if (name.startsWith(".env") && name !== ".env.example") return true;
  if (name.endsWith(".zip") || name.endsWith(".log") || name.endsWith(".pyc")) return true;
  return false;
}

function collectFiles(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === ".git" || ignoreDirs.has(entry)) continue;
    const full = path.join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      collectFiles(full, files);
      continue;
    }
    if (!stat.isFile() || skipFile(entry)) continue;
    const relative = path.relative(root, full).split(path.sep).join("/");
    if (relative === "worker/pkg/archive.generated.ts" || relative.endsWith(".zip")) continue;
    const data = readFileSync(full);
    if (entry !== ".env.example" && secretPattern.test(data.toString("utf8"))) {
      throw new Error(`Refusing to package possible secret in ${relative}`);
    }
    files.push({ name: `catechesis-reference-search/${relative}`, data, date: stat.mtime });
  }
  return files;
}

function u16(value) {
  const buffer = Buffer.alloc(2);
  buffer.writeUInt16LE(value);
  return buffer;
}

function u32(value) {
  const buffer = Buffer.alloc(4);
  buffer.writeUInt32LE(value >>> 0);
  return buffer;
}

function buildZip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;

  for (const file of files) {
    const name = Buffer.from(file.name, "utf8");
    const compressed = deflateRawSync(file.data);
    const crc = crc32(file.data);
    const { time, day } = dosStamp(file.date);
    const local = Buffer.concat([
      u32(0x04034b50),
      u16(20),
      u16(0x0800),
      u16(8),
      u16(time),
      u16(day),
      u32(crc),
      u32(compressed.length),
      u32(file.data.length),
      u16(name.length),
      u16(0),
      name,
      compressed,
    ]);
    const central = Buffer.concat([
      u32(0x02014b50),
      u16(20),
      u16(20),
      u16(0x0800),
      u16(8),
      u16(time),
      u16(day),
      u32(crc),
      u32(compressed.length),
      u32(file.data.length),
      u16(name.length),
      u16(0),
      u16(0),
      u16(0),
      u16(0),
      u32(0),
      u32(offset),
      name,
    ]);
    locals.push(local);
    centrals.push(central);
    offset += local.length;
  }

  const centralDir = Buffer.concat(centrals);
  const eocd = Buffer.concat([
    u32(0x06054b50),
    u16(0),
    u16(0),
    u16(files.length),
    u16(files.length),
    u32(centralDir.length),
    u32(offset),
    u16(0),
  ]);
  return Buffer.concat([...locals, centralDir, eocd]);
}

const files = collectFiles(root);
const zip = buildZip(files);
const outDir = path.join(root, "worker", "pkg");
mkdirSync(outDir, { recursive: true });
const modulePath = path.join(outDir, "archive.generated.ts");
const source = `// Generated by scripts/package.mjs. Do not edit. Contains no API secrets.\nexport const archiveBase64 = ${JSON.stringify(zip.toString("base64"))};\n`;
writeFileSync(modulePath, source);
console.log(`Packaged ${files.length} files (${zip.length} bytes) into worker module.`);
